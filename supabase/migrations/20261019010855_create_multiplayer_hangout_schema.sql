create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Player'
    check (char_length(display_name) between 1 and 24),
  avatar_color text not null default '#8b5cf6'
    check (avatar_color ~ '^#[0-9A-Fa-f]{6}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'Player'
    check (char_length(display_name) between 1 and 24),
  content text not null
    check (char_length(btrim(content)) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_created_at_idx
  on public.chat_messages (created_at desc);
create index if not exists chat_messages_user_id_idx
  on public.chat_messages (user_id);

alter table public.profiles enable row level security;
alter table public.chat_messages enable row level security;

drop policy if exists "Authenticated users can read profiles" on public.profiles;
create policy "Authenticated users can read profiles"
  on public.profiles for select to authenticated using (true);

drop policy if exists "Users can insert their own profile" on public.profiles;
create policy "Users can insert their own profile"
  on public.profiles for insert to authenticated with check ((select auth.uid()) = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

drop policy if exists "Authenticated users can read global chat" on public.chat_messages;
create policy "Authenticated users can read global chat"
  on public.chat_messages for select to authenticated using (true);

drop policy if exists "Users can send their own chat messages" on public.chat_messages;
create policy "Users can send their own chat messages"
  on public.chat_messages for insert to authenticated
  with check ((select auth.uid()) = user_id);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_name text;
begin
  requested_name := coalesce(new.raw_user_meta_data ->> 'display_name', split_part(coalesce(new.email, ''), '@', 1));
  requested_name := regexp_replace(btrim(requested_name), '[^[:alnum:] _-]', '', 'g');
  requested_name := left(nullif(requested_name, ''), 24);
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(requested_name, 'Player'))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();

create or replace function public.stamp_chat_display_name()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.content := btrim(new.content);
  select p.display_name into new.display_name
  from public.profiles as p
  where p.id = new.user_id;
  if new.display_name is null or new.display_name = '' then
    new.display_name := 'Player';
  end if;
  return new;
end;
$$;

drop trigger if exists stamp_chat_display_name_before_insert on public.chat_messages;
create trigger stamp_chat_display_name_before_insert
  before insert on public.chat_messages
  for each row execute procedure public.stamp_chat_display_name();

grant select, insert, update on public.profiles to authenticated;
